       COLLATE utf8mb4_unicode_ci =
     REPLACE(REPLACE(i.restaurante_excel, ' ', ''), CONVERT(0xC2A0 USING utf8mb4), '')
       COLLATE utf8mb4_unicode_ci
GROUP BY i.restaurante_excel;

